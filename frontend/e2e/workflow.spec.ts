import {test,expect} from '@playwright/test';
import path from 'node:path';
test('complete engineering investigation in the browser',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await expect(page.getByRole('heading',{name:/Don’t just debug/})).toBeVisible();
 await page.getByRole('button',{name:'Start an investigation'}).click();
 await page.getByLabel('Name',{exact:true}).fill('Browser Engineer');
 await page.getByLabel('Email',{exact:true}).fill(`browser-${Date.now()}@example.test`);
 await page.getByLabel('Password',{exact:true}).fill('browser-test-passphrase');
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Your projects'})).toBeVisible();
 await page.getByRole('button',{name:'New project'}).click();
 await page.getByLabel('Project name').fill('ESP32 / Simulated sensor failure');
 await page.getByLabel('Description',{exact:true}).fill('Reproducible address mismatch. All measurements are simulated.');
 await page.getByRole('button',{name:'Create project',exact:true}).click();
 await expect(page.getByRole('heading',{name:'ESP32 / Simulated sensor failure'})).toBeVisible();
 const demo=path.resolve('../demo/esp32-i2c');
 await page.getByLabel('Evidence file').setInputFiles(path.join(demo,'initial-evidence.zip'));
 await page.getByRole('button',{name:'Upload evidence'}).click();
 await expect(page.getByText('Evidence uploaded. Processing has started.')).toBeVisible();
 await page.getByRole('button',{name:'Dismiss notification'}).click();
 await page.getByLabel('Evidence category').selectOption('datasheet');
 await page.getByLabel('Evidence file').setInputFiles(path.join(demo,'sensor-datasheet.txt'));
 await page.getByRole('button',{name:'Upload evidence'}).click();
 await expect(page.locator('.file-list button').filter({hasText:'failure.csv'})).toContainText('ready',{timeout:120000});
 await expect(page.locator('.file-list button').filter({hasText:'sensor-datasheet.txt'})).toContainText('ready',{timeout:120000});
 await page.locator('.file-list button').filter({hasText:'failure.csv'}).click();
 await expect(page.locator('.uplot')).toBeVisible();
 await expect(page.getByText('0x92 NACK',{exact:true})).toBeVisible();
 await page.screenshot({path:'../docs/waveform-studio.png',fullPage:true});
 await page.getByRole('button',{name:'Investigations',exact:true}).click();
 await page.getByLabel('Observed failure').fill('SIMULATED ESP32 sensor does not ACK at configured address.');
 await page.getByRole('button',{name:'Create investigation',exact:true}).click();
 await page.getByRole('button',{name:'Correlate evidence'}).click();
 await expect(page.locator('.hypothesis').first()).toContainText('Firmware targets an incorrect I2C address');
 await expect(page.locator('.hypothesis').first()).toContainText('sensor-datasheet.txt');
 await page.screenshot({path:'../docs/diagnostic-workspace.png',fullPage:true});
 const top=page.locator('.hypothesis').first();await top.getByText('Record a test result',{exact:true}).click();
 await top.getByLabel('Actual observation').fill('SIMULATED verification: address 0x48 ACKs, original 0x49 NACKs. No physical measurement.');
 await top.getByLabel('Outcome',{exact:true}).selectOption('confirms');
 await top.getByRole('button',{name:'Record result'}).click();
 await expect(top).toContainText('user-confirmed');
 const download=page.waitForEvent('download');await page.getByRole('link',{name:'Export report'}).click();expect((await download).suggestedFilename()).toBe('benchtrace-report.md');
 await page.getByRole('button',{name:'Save to knowledge'}).click();
 await page.getByRole('button',{name:'Knowledge base',exact:true}).click();
 await expect(page.getByText('SIMULATED ESP32 sensor does not ACK at configured address.',{exact:true})).toBeVisible();
 await page.setViewportSize({width:390,height:844});await expect(page.locator('body')).toHaveJSProperty('scrollWidth',390);
 await page.screenshot({path:'../docs/mobile-workspace.png',fullPage:true});
 expect(errors).toEqual([]);
});
